#!/usr/bin/env python3
"""Assert every locale translates every string the plugin shows.

Nothing stopped a release from going out with English in the middle of a translated UI: the
Booklists screens (#258) shipped with 17 strings untranslated in 16 locales, and 1.0.60 added
Detailed logging the same way. A missing translation fails silently -- the English shows, and
nothing in the build or on the device says so.

The strings are taken from the code, not from l10n/koreader.pot: the template is only
regenerated by the release workflow, so a string added since the last release is in no
catalogue yet, and this has to catch exactly that. They are extracted the way the release
does it (xgettext, keyword T) from what the release ships: main.lua, _meta.lua and
zlibrary/*.lua. Each locale's .po is then merged against them without fuzzy matching, as the
release does, and every string must come out translated and not fuzzy.

Needs xgettext, msgmerge and msgattrib (gettext); without them this fails rather than skips,
like run.sh does for a missing python3 -- a check that cannot run must not look like a pass.

usage: python3 translation_coverage_check.py <plugin-root> [<koreader-root>]
"""
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

SHOW = 5  # untranslated strings listed per locale; the count is always given in full


def msgids(po_text):
    """The msgids of a .po text, with continuation lines joined; the header (empty msgid) skipped."""
    ids = []
    for m in re.finditer(r'^msgid ((?:"(?:[^"\\]|\\.)*"\n?)+)', po_text, re.M):
        text = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
        if text:
            ids.append(text)
    return ids


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)


def main():
    root = sys.argv[1]
    tools = ["xgettext", "msgmerge", "msgattrib"]
    missing_tools = [t for t in tools if shutil.which(t) is None]
    if missing_tools:
        print("  FAIL: %s not found, so translations could not be checked" % ", ".join(missing_tools))
        return 1

    sources = [os.path.join(root, "main.lua"), os.path.join(root, "_meta.lua")]
    sources += sorted(glob.glob(os.path.join(root, "zlibrary", "*.lua")))
    locales = sorted(d for d in glob.glob(os.path.join(root, "l10n", "*"))
                     if os.path.isfile(os.path.join(d, "koreader.po")))

    failed = 0
    with tempfile.TemporaryDirectory() as tmp:
        pot = os.path.join(tmp, "code.pot")
        done = run(["xgettext", "--language=Lua", "--from-code=UTF-8", "--keyword=T",
                    "--output=" + pot] + sources)
        if done.returncode != 0:
            print("  FAIL: xgettext could not read the sources:\n" + done.stderr)
            return 1
        with open(pot, encoding="utf-8") as fh:
            wanted = msgids(fh.read())
        if len(wanted) < 100:
            print("  FAIL: only %d strings extracted; the extraction is broken" % len(wanted))
            return 1
        print("  [ok  ] %d strings extracted from the code" % len(wanted))

        for d in locales:
            loc = os.path.basename(d)
            merged = os.path.join(tmp, loc + ".po")
            done = run(["msgmerge", "--quiet", "--no-fuzzy-matching", "--no-wrap",
                        os.path.join(d, "koreader.po"), pot, "-o", merged])
            if done.returncode != 0:
                print("  [FAIL] %s: msgmerge failed: %s" % (loc, done.stderr.strip()))
                failed += 1
                continue
            gaps = []
            for flag in ("--untranslated", "--only-fuzzy"):
                out = run(["msgattrib", flag, "--no-obsolete", "--no-wrap", merged])
                gaps += msgids(out.stdout)
            if gaps:
                failed += 1
                listed = "; ".join('"%s"' % g for g in gaps[:SHOW])
                more = " (and %d more)" % (len(gaps) - SHOW) if len(gaps) > SHOW else ""
                print("  [FAIL] %s: %d untranslated: %s%s" % (loc, len(gaps), listed, more))
            else:
                print("  [ok  ] %s translates every string" % loc)

    print("\n  %d locales, %d with untranslated strings" % (len(locales), failed))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
